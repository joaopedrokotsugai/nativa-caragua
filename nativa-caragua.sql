

CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(10) NOT NULL DEFAULT 'ativa'
        CHECK (status IN ('ativa', 'desativa')),
    exclusao_solicitada_em TIMESTAMP,
    role VARCHAR(10) NOT NULL DEFAULT 'usuario'
        CHECK (role IN ('usuario', 'admin'))
);

CREATE TABLE IF NOT EXISTS campanhas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    data TIMESTAMP NOT NULL,
    local VARCHAR(200) NOT NULL,
    vagas INTEGER NOT NULL CHECK (vagas >= 0),
    imagem VARCHAR(255),
    data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS projetos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    descricao TEXT NOT NULL,
    meta NUMERIC(10,2) NOT NULL CHECK (meta >= 0),
    valor_arrecadado NUMERIC(10,2) NOT NULL DEFAULT 0.00
        CHECK (valor_arrecadado >= 0),
    imagem VARCHAR(255),
    data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    data_encerramento DATE
);

CREATE TABLE IF NOT EXISTS doacoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL REFERENCES usuarios(id),
    id_projeto INTEGER NOT NULL REFERENCES projetos(id),
    valor NUMERIC(10,2) NOT NULL CHECK (valor > 0),
    data TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS denuncias (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL REFERENCES usuarios(id),
    titulo VARCHAR(150) NOT NULL,
    descricao TEXT NOT NULL,
    local VARCHAR(200) NOT NULL,
    imagem VARCHAR(255),
    data TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS participacoes (
    id_usuario INTEGER NOT NULL REFERENCES usuarios(id),
    id_campanha INTEGER NOT NULL REFERENCES campanhas(id),
    data_inscricao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_usuario, id_campanha)
);


-- Conferir a estrutura das tabelas

SELECT
    table_name,
    column_name,
    data_type
FROM information_schema.columns
WHERE table_schema = 'public'
  AND table_name IN (
      'usuarios',
      'participacoes',
      'doacoes',
      'denuncias',
      'projetos',
      'campanhas'
  )
ORDER BY table_name, ordinal_position;


-- Listar campanhas futuras

SELECT id, titulo, data, local, vagas, imagem
FROM campanhas
WHERE data >= CURRENT_TIMESTAMP
ORDER BY data ASC;


-- Listar projetos disponíveis

SELECT id, titulo, descricao, meta, valor_arrecadado,
       imagem, data_encerramento
FROM projetos
WHERE data_encerramento IS NULL
   OR data_encerramento >= CURRENT_DATE
ORDER BY id DESC;


-- Conferir os usuários e seus perfis

SELECT id, nome, email, role
FROM usuarios;
